#!/usr/bin/env bash
# Regenerates mod/hooks/fixtures/pixels.ts: six real `frame --json --pixels`
# grids recorded from the binary in a sandbox (never the real state dir).
#
#   bash mod/scripts/record-pixel-fixtures.sh
#
# A .ts module, not .json: the plugin test runtime only loads code files.
# Each case hatches a fresh kitten, then sets the level and the clock-derived
# mood inputs with jq on the sandbox state.json (level is not linear in feeds).
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
out="$repo/mod/hooks/fixtures/pixels.ts"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

eval "$(bash "$repo/mod/scripts/dev-sandbox.sh" "$tmp/sandbox")"
state="$PURR_SANDBOX_STATE/state.json"
export HOME="$tmp/home"
mkdir -p "$HOME"

# label | hatch args (";"-separated) | level | seconds since last fed | context pct
cases=(
  "tabby kitten calm|--breed;Tabby|3|600|5"
  "siamese young happy|--breed;Siamese|20|0|5"
  "maine coon adult alert|--breed;Maine Coon|60|600|50"
  "void cat legendary shiny adult panic|--breed;Void Cat;--rarity;legendary;--shiny|60|600|95"
  "calico adult hungry|--breed;Calico|60|7200|5"
  "chimera legendary kitten sleep|--breed;Chimera;--rarity;legendary|3|25200|5"
)

echo '[]' > "$tmp/out.json"
for c in "${cases[@]}"; do
  IFS='|' read -r label hatch level fed_ago ctx <<< "$c"
  rm -f "$state" "$PURR_SANDBOX_STATE/.purr.lock"
  IFS=';' read -ra hatch_args <<< "$hatch"
  purrgotchi hatch "${hatch_args[@]}" > /dev/null 2>&1
  now="$(date +%s)"
  jq --argjson l "$level" --argjson f "$((now - fed_ago))" '.level = $l | .last_fed_at = $f' "$state" > "$state.new"
  mv "$state.new" "$state"
  purrgotchi frame --json --pixels --context-pct "$ctx" > "$tmp/frame.json"
  jq -r --arg label "$label" '"\($label): \(.breed) \(.rarity) \(.stage) \(.mood) shiny=\(.shiny)"' "$tmp/frame.json" >&2
  jq -c --arg label "$label" '{label: $label, pixels: .pixels}' "$tmp/frame.json" > "$tmp/case.json"
  jq -c --slurpfile c "$tmp/case.json" '. + $c' "$tmp/out.json" > "$tmp/out.next" && mv "$tmp/out.next" "$tmp/out.json"
done

mkdir -p "$(dirname "$out")"
{
  echo '// Generated by mod/scripts/record-pixel-fixtures.sh from the binary; do not edit.'
  echo "export const pixelFixtures: { label: string; pixels: (string | null)[][] }[] = $(jq -c . "$tmp/out.json")"
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)" >&2
